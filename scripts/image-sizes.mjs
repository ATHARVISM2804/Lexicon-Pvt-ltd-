// Regenerates src/data/imageSizes.js: the widths available for each photo in
// /public/images (the original plus any -640/-1080 WebP versions), so <Figure>
// can offer the browser a responsive srcset. Run after adding photos:
//   node scripts/image-sizes.mjs
import { readdirSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";

const dir = "public/images";
const files = readdirSync(dir);
const out = {};
for (const f of files.filter((f) => f.endsWith(".jpg"))) {
  const base = f.slice(0, -4);
  const width = Number(
    execFileSync("sips", ["-g", "pixelWidth", `${dir}/${f}`]).toString().match(/pixelWidth: (\d+)/)[1]
  );
  const widths = [640, 1080].filter((w) => files.includes(`${base}-${w}.webp`));
  out[`/images/${f}`] = [...widths, width];
}
writeFileSync(
  "src/data/imageSizes.js",
  `/* Generated by scripts/image-sizes.mjs — widths available per photo. */\nexport const imageSizes = ${JSON.stringify(out, null, 2)};\n`
);
console.log(Object.keys(out).length, "images");
